export function getStateGreeting(stateId: string): StateGreeting | undefined {
  if (!stateId) return undefined
  const clean = stateId.toLowerCase().trim()
  if (GREETINGS_DATA[clean]) return GREETINGS_DATA[clean]

  // Slug aliases
  if (clean === "up") return GREETINGS_DATA["uttar-pradesh"]
  if (clean === "tamilnadu") return GREETINGS_DATA["tamil-nadu"]
  if (clean === "wb") return GREETINGS_DATA["west-bengal"]
  if (clean === "mp") return GREETINGS_DATA["madhya-pradesh"]
  if (clean === "hp") return GREETINGS_DATA["himachal-pradesh"]
  if (clean === "jk" || clean === "jammu") return GREETINGS_DATA["jammu-kashmir"]
  if (clean === "ap") return GREETINGS_DATA["andhra-pradesh"]
  if (clean === "uk") return GREETINGS_DATA["uttarakhand"]
  if (clean === "dnh-dd") return GREETINGS_DATA["dadra-nagar-haveli-daman-diu"]

  // Lookup by state name
  const match = Object.values(GREETINGS_DATA).find(
    (g) => g.stateName.toLowerCase() === clean || g.stateId.toLowerCase() === clean
  )
  return match
}
